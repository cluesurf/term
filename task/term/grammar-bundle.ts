// THE GRAMMAR TEXTS TERM READS AT RUN TIME, baked into the build (decision note/project/term/mill/decision/003): each
// grammar's text into a Term module its reader loads (`note-grammar-text`, `deck-grammar-text`), so the reader runs the
// grammar itself, browser-safe and with no file read at run time. The grammar files are the source and each module is
// derived from them, never edited. The one bundler: every baked grammar is written here and held by one `--check`.
//
//   pnpm term:grammar-bundle            write what changed
//   pnpm term:grammar-bundle --check    write nothing, exit 1 when a baked grammar is not its source
//
// A grammar is either one file as written (the text grammars' mine.tree) or the load closure of a mill entry
// (`grammarTextOf`, the walker that reads each file with the real parser and resolves each `load` by the package path
// rule): the deck and lock grammars the package manager reads deck.tree and lock.tree with. A closure with problems is
// refused, and nothing is written.
//
// note/project/term/mill/02-role-scopes.md, "What the build does with it".

import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { TERM_ROOT } from './root'

const ROOT = TERM_ROOT
const TERM_CONFIG = join(TERM_ROOT, 'tsconfig.json')

// The closure walker is compiler code, reached by the Term package's `@term/make` paths, which the repository's own
// tsconfig does not map: run from the root (`pnpm term:grammar-bundle`), the script runs itself again under the Term
// package's tsconfig
if (process.env['TSX_TSCONFIG_PATH'] !== TERM_CONFIG) {
  const again = spawnSync(process.execPath, [...process.execArgv, process.argv[1]!, ...process.argv.slice(2)], {
    stdio: 'inherit',
    env: { ...process.env, TSX_TSCONFIG_PATH: TERM_CONFIG },
  })

  process.exit(again.status ?? 1)
}

const NOTE = join(TERM_ROOT, 'deck/mill/code/text/note')
const LATEX = join(TERM_ROOT, 'deck/mill/code/text/latex')
const MILL_TREE = join(TERM_ROOT, 'deck/mill/code/tree')
const PACKAGE = join(TERM_ROOT, 'deck/deck/code/package')

type Grammar = {
  // where the baked module goes, and the task that gives the text
  baked: string
  task: string
  // the header's two comment lines: what the text is made from, and what to edit instead
  header: [string, string]
  // the text: the file as written, or the load closure of a mill entry
  text: () => Promise<string>
}

// a grammar file as written
const asWritten = (source: string) => async () => readFileSync(source, 'utf8').replace(/\n$/, '')

// the load closure of a mill entry, refused when the walk reports a problem
function closureOf(entry: string): () => Promise<string> {
  return async () => {
    const { grammarTextOf } = await import('@term/make/code/compile/mill-load')
    const { text, problems } = grammarTextOf(MILL_TREE, entry)

    if (problems.length > 0) {
      for (const problem of problems) {
        console.log(`  problem: ${problem}`)
      }

      throw new Error(`grammar-bundle: ${problems.length} problem(s) reading the load closure of ${entry.slice(ROOT.length + 1)}`)
    }

    // whole, a closing line break and all: the module answers the closure byte for byte
    return text
  }
}

// a text grammar's header: its one mine.tree beside the module
const MINE_HEADER: [string, string] = [
  '# GENERATED by `pnpm term:grammar-bundle` from ./mine.tree, the grammar as written. Never edit this file: edit',
  '# mine.tree and run it again. `pnpm term:grammar-bundle --check` fails while the two differ.',
]

// a mill grammar's header: the load closure of its entry
const closureHeader = (entry: string): [string, string] => [
  `# GENERATED by \`pnpm term:grammar-bundle\` from the load closure of ${entry}. Never edit this`,
  '# file: edit the grammar and run it again. `pnpm term:grammar-bundle --check` fails while the two differ.',
]

const GRAMMARS: Grammar[] = [
  { baked: join(NOTE, 'grammar.tree'), task: 'note-grammar-text', header: MINE_HEADER, text: asWritten(join(NOTE, 'mine.tree')) },
  { baked: join(LATEX, 'grammar.tree'), task: 'latex-grammar-text', header: MINE_HEADER, text: asWritten(join(LATEX, 'mine.tree')) },
  {
    baked: join(PACKAGE, 'deck-grammar-text.tree'),
    task: 'deck-grammar-text',
    header: closureHeader('deck/mill/code/tree/deck/mine.tree'),
    text: closureOf(join(MILL_TREE, 'deck', 'mine.tree')),
  },
  {
    baked: join(PACKAGE, 'lock-grammar-text.tree'),
    task: 'lock-grammar-text',
    header: closureHeader('deck/mill/code/tree/deck/lock/mine.tree'),
    text: closureOf(join(MILL_TREE, 'deck', 'lock', 'mine.tree')),
  },
]

// a line of the grammar as the content of a Term text literal: every character the literal reads as syntax escaped
function escaped(line: string): string {
  return line.replace(/[\\<>{}]/g, character => `\\${character}`)
}

function bakedOf(text: string, task: string, header: [string, string]): string {
  const lines = text.split('\n')
  const out = [
    ...header,
    '',
    'load @term/base/list',
    '  find join',
    '',
    `task ${task}`,
    '  like text',
    '',
    '  save lines, make list',
  ]

  for (const line of lines) {
    out.push(`  push(lines, <${escaped(line)}>)`)
  }

  out.push('  back join(lines, <\\n>)', '')

  return out.join('\n')
}

async function bake(): Promise<void> {
  const check = process.argv.includes('--check')
  const wanted: { grammar: Grammar; want: string }[] = []
  let refused = 0

  // every text first: a refused closure writes nothing at all
  for (const grammar of GRAMMARS) {
    try {
      wanted.push({ grammar, want: bakedOf(await grammar.text(), grammar.task, grammar.header) })
    } catch (error) {
      refused++
      console.log(`  REFUSED ${grammar.baked.slice(ROOT.length + 1)}: ${(error as Error).message}`)
    }
  }

  if (refused > 0) {
    process.exitCode = 1

    return
  }

  let stale = 0

  for (const { grammar, want } of wanted) {
    const have = existsSync(grammar.baked) ? readFileSync(grammar.baked, 'utf8') : undefined

    if (have === want) {
      console.log(`  unchanged ${grammar.baked.slice(ROOT.length + 1)}`)
      continue
    }

    if (check) {
      stale++
      console.log(`  STALE ${grammar.baked.slice(ROOT.length + 1)}: run pnpm term:grammar-bundle`)
      continue
    }

    writeFileSync(grammar.baked, want)
    console.log(`  wrote ${grammar.baked.slice(ROOT.length + 1)}`)
  }

  if (stale > 0) {
    process.exitCode = 1
  }
}

void bake()
