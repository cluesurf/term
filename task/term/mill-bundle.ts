// Bake the code role's mill into the compiler.
//
// The compiler reads Term through the grammar in `deck/mill/code/tree/code`. It cannot go looking for those files at
// run time: a compiled project need not depend on `@term/mill`, and `host/line.js` is a single bundled file with
// no package tree beside it. So the merged grammar text is generated into a TypeScript module the compiler
// imports, the same way `pnpm run make:read` bakes the parser into zone's shim.
//
// Run from the Term root. Reports by default; writes only with `--commit`.
// Re-run after any change under deck/mill/code/tree/code; `pnpm term:mint-parity` fails if the baked copy is stale.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { loadRoleGrammar } from '@term/make/code/compile/mill-load'
import { grammarReadText } from '@term/make/code/compile/mill-grammar-text'
import { TERM_ROOT } from './root'

const TERM = TERM_ROOT
const MILL = join(TERM, 'deck/mill/code/tree')
const ROLE = process.argv.find(a => a.startsWith('--role='))?.slice(7) ?? 'code'
const OUT = join(
  TERM,
  'deck/make/code/compile/mill-grammar.generated.ts',
)
const commit = process.argv.includes('--commit')

function main(): void {
  const grammar = loadRoleGrammar(MILL, ROLE)

  for (const problem of grammar.problems) {
    console.log(`  problem: ${problem}`)
  }

  if (grammar.collisions.length > 0) {
    for (const c of grammar.collisions) {
      console.log(`  collision: ${c.half} ${c.name}`)
    }

    console.log('mill-bundle: refusing to bake a grammar with collisions')
    process.exitCode = 1

    return
  }

  const quote = (text: string): string =>
    JSON.stringify(text)

  const built = `// GENERATED by \`pnpm term:mill-bundle\`. Do not edit.
//
// The ${ROLE} role's mill, merged from deck/mill/code/tree/${ROLE}: the \`mine\` grammar that says how to read a
// \`.tree\` file and the \`mint\` grammar that says what to build from it. Baked in because the compiler cannot
// look for those files at run time (see task/term/mill-bundle.ts for why).
//
// ${grammar.mine.size} mine rules, ${grammar.mint.size} mint rules, from ${grammar.files.length} files.

export const MINE_SOURCE = ${quote(grammar.mineText)}

export const MINT_SOURCE = ${quote(grammar.mintText)}

// the two as compile/mill-running.tree reads them (compile/mill-grammar-text.tree), which is all the compiler itself needs
export const READ_GRAMMAR = ${quote(grammarReadText(grammar.mineText, grammar.mintText))}

export function readGrammar(): { mine: Map<string, any>; mint: Map<string, any>; lean: Map<string, boolean> } {
  const read = JSON.parse(READ_GRAMMAR) as { mine: [string, any][]; mint: [string, any][]; lean: string[] }

  return {
    mine: new Map(read.mine),
    mint: new Map(read.mint),
    lean: new Map(read.lean.map(rule => [rule, true])),
  }
}
`

  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''

  console.log(
    `mill-bundle: ${grammar.mine.size} mine rules, ${grammar.mint.size} mint rules, ${grammar.files.length} files`,
  )

  if (built === current) {
    console.log('mill-bundle: the baked grammar is current')

    return
  }

  if (commit) {
    writeFileSync(OUT, built)
    console.log(`mill-bundle: wrote ${OUT}`)
  } else {
    console.log(
      'mill-bundle: the baked grammar is STALE, pass --commit to write it',
    )
    process.exitCode = 1
  }
}

main()
