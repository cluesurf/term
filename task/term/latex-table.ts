// every macro KaTeX writes as a function rather than a text, each read by the reader's builtin of the same name
const BUILTIN_MACROS = new Set([
  '\\noexpand', '\\expandafter', '\\@firstoftwo', '\\@secondoftwo', '\\@ifnextchar', '\\TextOrMath', '\\char',
  '\\newcommand', '\\renewcommand', '\\providecommand', '\\message', '\\errmessage', '\\show', '\\dots', '\\dotso',
  '\\dotsc', '\\cdots', '\\tag@literal', '\\bra@ket', '\\bra@set',
])

// ---- one field of a row ----
//
// A field is written as itself when every character in it is a letter, a number, punctuation or a symbol, which is
// how a person reads `\alpha` or `≤` in the file. Anything else (a space, a combining mark, a no-break space, a
// zero-width one) is written `=` and its code points in hex, dot separated, so nothing invisible is ever in the file.
// A field that begins with `=` is written the same way, so the two never meet.

const PLAIN = /^[\p{L}\p{N}\p{P}\p{S}]+$/u

function field(value: string): string {
  if (value === '' || (PLAIN.test(value) && !value.startsWith('=') && !/\p{M}/u.test(value))) {
    return value
  }

  return '=' + [...value].map(c => c.codePointAt(0)!.toString(16).padStart(4, '0')).join('.')
}

function row(values: string[]): string {
  return values.map(field).join('\t')
}

function groupsOf(table: Record<string, Spec>): Map<Spec, string[]> {
  const out = new Map<Spec, string[]>()

  for (const [name, spec] of Object.entries(table)) {
    const names = out.get(spec) ?? []

    names.push(name)
    out.set(spec, names)
  }

  return out
}

// the flags a spec sets, as letters: t allowed in text, n NOT allowed in math, a allowed in an argument, i infix,
// p primitive
function flagsOf(spec: Spec): string {
  return [
    spec.allowedInText ? 't' : '',
    spec.allowedInMath === false ? 'n' : '',
    spec.allowedInArgument ? 'a' : '',
    spec.infix ? 'i' : '',
    spec.primitive ? 'p' : '',
  ].join('')
}

// every spec of a registry as rows, each name with the handler its spec maps to
function specRows(table: Record<string, Spec>, handlers: Record<string, string>, problems: string[]): string[] {
  const rows: string[] = []

  for (const [spec, names] of groupsOf(table)) {
    const handler = handlers[names[0]]

    if (!handler) {
      problems.push(`no reader handler for KaTeX's ${spec.type} spec ${names.join(' ')}: add one here and to read.tree`)
      continue
    }

    for (const name of names) {
      rows.push(row([
        name,
        handler,
        String(spec.numArgs),
        String(spec.numOptionalArgs ?? 0),
        (spec.argTypes ?? []).join(','),
        flagsOf(spec),
      ]))
    }
  }

  return rows
}

// ---- the module ----

// a row as the content of a Term text literal: every character the literal reads as syntax escaped, and the tab
// that separates fields written as the literal's own `\t`
function literal(text: string): string {
  return text.replace(/[\\<>{}]/g, character => `\\${character}`).replace(/\t/g, '\\t')
}

// rows packed several to a line, so the module stays short for the compiler and every row still reads on its own
function task(name: string, note: string, rows: string[]): string[] {
  const out = ['', `# ${note}`, `task ${name}`, '  like text', '', '  save chunks, make list']
  let line = ''

  for (const one of rows) {
    const piece = literal(one) + '\\n'

    if (line !== '' && line.length + piece.length > 100) {
      out.push(`  push(chunks, <${line}>)`)
      line = ''
    }

    line += piece
  }

  if (line !== '') {
    out.push(`  push(chunks, <${line}>)`)
  }

  out.push('  back join(chunks, <>)')

  return out
}

async function main(): Promise<void> {
  if (!existsSync(join(KATEX, 'src/Parser.ts'))) {
    console.error(`no KaTeX checkout at ${KATEX}: clone it with git clone --depth 1 https://github.com/KaTeX/KaTeX`)
    process.exit(1)
  }

  const { functions, environments, macros, symbols, scripts, accents, composed } = await registries()
  const version = JSON.parse(readFileSync(join(KATEX, 'package.json'), 'utf8')).version as string
  const problems: string[] = []

  const functionRows = specRows(functions, HANDLERS, problems)
  const environmentRows = specRows(environments, ENVIRONMENT_HANDLERS, problems)

  const symbolRows: string[] = []

  for (const mode of ['math', 'text']) {
    for (const [name, info] of Object.entries(symbols[mode])) {
      symbolRows.push(row([mode, name, info.group, info.font, info.replace ?? '']))
    }
  }

  const macroRows: string[] = []

  for (const [name, value] of Object.entries(macros)) {
    if (typeof value === 'string') {
      macroRows.push(row([name, 'text', value]))
    } else if (typeof value === 'function' && BUILTIN_MACROS.has(name)) {
      macroRows.push(row([name, 'builtin', '']))
    } else {
      problems.push(`KaTeX's macro ${name} is a ${typeof value} the reader has no builtin for`)
    }
  }

  for (const name of BUILTIN_MACROS) {
    if (typeof macros[name] !== 'function') {
      problems.push(`the builtin ${name} is no longer a function macro in KaTeX`)
    }
  }

  const scriptRows = Object.entries(scripts.uSubsAndSups).map(([character, value]) =>
    row([character, value, scripts.unicodeSubRegEx.test(character) ? 'sub' : 'sup']))
  const accentRows = Object.entries(accents).map(([mark, spelled]) => row([mark, spelled.text, spelled.math ?? '']))
  const composedRows = Object.entries(composed).map(([character, parts]) => row([character, parts]))

  // KaTeX's `supportedCodepoint` asked of every UTF-16 unit, the units it answers yes for written as ranges: its own
  // block list is not exported, and what it answers is what strict mode reads
  const { supportedCodepoint } = await load<{ supportedCodepoint: (code: number) => boolean }>('src/unicodeScripts.ts')
  const blockRows: string[] = []
  let start = -1

  for (let code = 0; code <= 0x10000; code++) {
    const supported = code < 0x10000 && supportedCodepoint(code)

    if (supported && start < 0) {
      start = code
    } else if (!supported && start >= 0) {
      blockRows.push(row([String(start), String(code - 1)]))
      start = -1
    }
  }

  const { extraLatin } = await load<{ extraLatin: string }>('src/symbols.ts')
  const extraRows = [...extraLatin].map(character => row([character]))

  if (problems.length > 0) {
    for (const problem of problems) {
      console.error(`  ${problem}`)
    }

    process.exit(1)
  }

  const module = [
    `# GENERATED by \`pnpm term:latex-table --commit\` from KaTeX ${version} (commit ${commitOf(KATEX)}), its src/`,
    '# registries read as they stand. Never edit this file: change task/term/latex-table.ts, or the KaTeX it reads, and',
    '# run it again. `pnpm term:latex-table --check` fails while the two differ. KaTeX is MIT licensed, Copyright (c)',
    '# 2013-2020 Khan Academy and other contributors.',
    '#',
    '# Each task answers rows, one to a line, fields separated by a tab. A field holding a character nobody could see',
    '# (a space, a combining mark, a no-break space) is written `=` and its code points in hex, dot separated: `=00a0`.',
    '# ./read.tree `make-latex-table` reads them into hashes once.',
    '',
    'load @term/base/list',
    '  find join',
    ...task('latex-symbol-rows', `every symbol: mode, name, group, font, the character it stands for. ${symbolRows.length} rows`, symbolRows),
    ...task('latex-function-rows', `every function: name, the reader's handler, arguments, optional arguments, argument types, flags (t text, n not math, a in an argument, i infix, p primitive). ${functionRows.length} rows`, functionRows),
    ...task('latex-environment-rows', `every environment: name, the reader's handler, arguments, optional arguments, argument types, flags. ${environmentRows.length} rows`, environmentRows),
    ...task('latex-macro-rows', `every builtin macro: name, \`text\` and its expansion, or \`builtin\` for one the reader computes. ${macroRows.length} rows`, macroRows),
    ...task('latex-script-rows', `every Unicode sub- and superscript character: the character, what it stands for, sub or sup. ${scriptRows.length} rows`, scriptRows),
    ...task('latex-accent-rows', `every combining accent: the mark, its text-mode command, its math-mode command. ${accentRows.length} rows`, accentRows),
    ...task('latex-composed-rows', `every precomposed accented letter: the character, the letter and its combining marks. ${composedRows.length} rows`, composedRows),
    ...task('latex-block-rows', `every run of UTF-16 units KaTeX's \`supportedCodepoint\` answers yes for, first and last in decimal. ${blockRows.length} rows`, blockRows),
    ...task('latex-extra-latin-rows', `KaTeX's \`extraLatin\`: the Latin-1 letters its math fonts carry that LaTeX reads only in text. ${extraRows.length} rows`, extraRows),
    '',
  ].join('\n')

  console.log(`KaTeX ${version}: ${symbolRows.length} symbols, ${functionRows.length} functions, ${environmentRows.length} environments, ${macroRows.length} macros`)

  for (const [file, want] of [[TABLE, module], [GRAMMAR, grammarWithTail()]]) {
    const have = existsSync(file) ? readFileSync(file, 'utf8') : undefined
    const relative = file.slice(ROOT.length + 1)

    if (have === want) {
      console.log(`  unchanged ${relative}`)
    } else if (process.argv.includes('--check')) {
      console.log(`  STALE ${relative}: run pnpm term:latex-table --commit`)
      process.exitCode = 1
    } else if (process.argv.includes('--commit')) {
      writeFileSync(file, want)
      console.log(`  wrote ${relative}`)
    } else {
      console.log(`  would write ${relative} (${want.length} bytes): pass --commit`)
    }
  }
}

main()
