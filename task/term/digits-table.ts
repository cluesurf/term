// pnpm term:digits-table [--commit] [--out <file>]
//
// term/decisions-2026-10/locale item 0003: the powers of ten Schubfach (Giulietti 2020, "The Schubfach way to render
// doubles") reads to write the shortest decimal digits of a float
// (deck/base/code/text/format/digits.tree). For each k from -324 to 292 (617 of them) the 126-bit integer
//
//   g(k) = floor(10^-k * 2^(125 - f)) + 1,   f = floor(log2(10^-k))
//
// so that 2^125 <= g < 2^126. The paper's section 9.8.3 writes it as g1 * 2^63 + g0, and the Java reference
// (java.lang.DoubleToDecimal) as two 63-bit constants. Here it is FOUR 32-bit limbs, because the Term product that
// reads it (deck/base/code/float/wide.tree) works on 32-bit limbs, which TypeScript holds exactly where it cannot hold
// a 64-bit word.
//
// Written as four top-level text constants, one per limb (limb 0 is the least significant), each 617 fixed-width
// records of ten decimal digits in order of k, so a read is `substring` at (k + 324) * 10 and `parse-integer`. 6,170
// bytes each, under the 16,000 a text constant may hold (locale/spec.md 4.3).
//
// Computed with BigInt, exact: nothing here is a float, and nothing is copied from the Java source. The proof that
// the table is right is test/stdlib/float-digits.ts (the shortest digits of 20,000 floats against JavaScript's own
// Number toString on every backend), and the generator's own self-check: every g is in range and no g is a power of
// ten's exact image (g is never exact, which is why the +1 is there).
//
// Reports by default: the entry count, the first and last entry, and whether the file on disk has drifted (exit 1
// when it has). `--commit` writes it.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CALLER_CWD, TERM_ROOT } from './root'

const REPO = TERM_ROOT
const DEFAULT_OUT = join(TERM_ROOT, 'deck/base/code/text/format/digits-table.tree')

export const K_MIN = -324
export const K_MAX = 292

const args = process.argv.slice(2)
const commit = args.includes('--commit')
const out = args.includes('--out') ? resolve(CALLER_CWD, args[args.indexOf('--out') + 1]!) : DEFAULT_OUT

const bitLength = (n: bigint): number => n.toString(2).length

// floor(log2(10^e)), exact, for any integer e
export function floorLog2Pow10(e: number): number {
  if (e >= 0) {
    return bitLength(10n ** BigInt(e)) - 1
  }

  // 10^e = 1 / 10^m, so floor(log2) = -ceil(log2(10^m)) = -bitLength(10^m - 1)
  return -bitLength(10n ** BigInt(-e) - 1n)
}

export function powerOf(k: number): bigint {
  const f = floorLog2Pow10(-k)
  const shift = 125 - f

  if (-k >= 0) {
    const value = 10n ** BigInt(-k)

    if (shift >= 0) {
      return value << BigInt(shift)
    }

    const unit = 1n << BigInt(-shift)

    return (value + unit - 1n) / unit
  }

  const divisor = 10n ** BigInt(k)

  return ((1n << BigInt(shift)) + divisor - 1n) / divisor
}

const limbs: string[][] = [[], [], [], []]

for (let k = K_MIN; k <= K_MAX; k++) {
  const g = powerOf(k)

  if (g < 1n << 125n || g >= 1n << 126n) {
    throw new Error(`g(${k}) is out of range`)
  }

  for (let limb = 0; limb < 4; limb++) {
    limbs[limb]!.push(String((g >> BigInt(32 * limb)) & 0xffffffffn).padStart(10, '0'))
  }
}

const count = K_MAX - K_MIN + 1
const body = [
  `# GENERATED by \`pnpm term:digits-table --commit\`, exactly, with BigInt. Do not edit: rerun. \`pnpm term:digits-table\``,
  `# fails when this file drifts. ./digits.tree reads it.`,
  `#`,
  `# ${count} powers of ten for k from ${K_MIN} to ${K_MAX}, each the 126-bit integer g(k) = floor(10^-k * 2^(125 - f)) + 1`,
  `# with f = floor(log2(10^-k)), as four 32-bit limbs of ten decimal digits each (Schubfach, Giulietti 2020, 9.8.3).`,
  `# Limb 0 is the least significant. The record for k starts at position (k - ${K_MIN}) * 10 of each text.`,
  ``,
  `host power-count, code ${count}`,
  ``,
  ...limbs.flatMap((list, limb) => [`host power-limb-${limb}, text <${list.join('')}>`, ``]),
]
  .join('\n')
  .replace(/\n+$/, '\n')

if (import.meta.url === `file://${process.argv[1]}`) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  const same = current === body

  console.log(`${count} entries, k ${K_MIN} to ${K_MAX}, ${body.length} bytes`)
  console.log(`first ${powerOf(K_MIN).toString(16)}`)
  console.log(`last  ${powerOf(K_MAX).toString(16)}`)

  if (commit) {
    writeFileSync(out, body)
    console.log(`wrote ${relative(REPO, out)}`)
  } else if (same) {
    console.log(`${relative(REPO, out)} is current`)
  } else {
    console.log(`${relative(REPO, out)} has drifted: run with --commit`)
    process.exit(1)
  }
}
