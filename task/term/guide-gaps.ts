// Every term.surf guide page's `What is missing` section, gathered into one markdown file, page by page in route
// order, so the gaps the guides admit can be planned against as one list (note/project/term/guides/research/gaps/plan.md).
//
//   pnpm term:guide-gaps            print the capture and its count
//   pnpm term:guide-gaps --commit   write it to note/project/term/guides/research/gaps/guide-gaps.md
//
// The pages are the source of truth. A gap closes when its line leaves the page, and this capture is regenerated in
// the same change, so the file cannot say what the pages no longer do.

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { TERM_ROOT, parentRoot } from './root'

// run from the repository root, as the alias does
const ROOT = TERM_ROOT
const BODY = (): string => join(parentRoot(), 'mesh/site/term.surf/home/site/component/page/guides/body')
const OUT = (): string => join(parentRoot(), 'note/project/term/guides/research/gaps/guide-gaps.md')
const COMMIT = process.argv.includes('--commit')

// a JSX text literal, `{'...'}`, `{"..."}` or a template literal, escapes included
const LITERAL = /\{'((?:[^'\\]|\\.)*)'\}|\{"((?:[^"\\]|\\.)*)"\}|\{`((?:[^`\\]|\\.)*)`\}/g
// inline code, which keeps its backticks in the capture
const CODE = /<Code>\s*\{'((?:[^'\\]|\\.)*)'\}\s*<\/Code>/g
// one block of a section, from its `form:` to the next block's
const BLOCK = /form: '(\w+)'([\s\S]*?)(?=\n\s*\{\s*\n\s*form: '|$)/g

type Entry = { form: 'item'; text: string } | { form: 'code'; kind: string; text: string }

function unescape(text: string): string {
  return text.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\n/g, ' ')
}

// the text of one bullet: its literals in order, inline code as `code`
function fragmentText(fragment: string): string {
  const marked = fragment.replace(CODE, (_, code: string) => `{'\`${code}\`'}`)
  const parts = [...marked.matchAll(LITERAL)].map(m => unescape(m[1] ?? m[2] ?? m[3] ?? ''))

  return parts.join('').replace(/\s+/g, ' ').trim()
}

// the source of the `What is missing` section, up to the next section's title
function sectionOf(source: string): string | undefined {
  const at = source.indexOf("title: 'What is missing'")

  if (at < 0) {
    return undefined
  }

  const rest = source.slice(at + 10)
  const end = rest.search(/\n {4,6}title: '/)

  return end < 0 ? rest : rest.slice(0, end)
}

function entriesOf(section: string): Entry[] {
  const out: Entry[] = []

  for (const [, form, body] of section.matchAll(BLOCK)) {
    if (form === 'code') {
      const text = body!.match(/text: `((?:[^`\\]|\\.)*)`/)
      const kind = body!.match(/kind: '(\w+)'/)

      if (text) {
        out.push({ form: 'code', kind: kind?.[1] ?? '', text: text[1]!.replace(/\\`/g, '`') })
      }

      continue
    }

    const items = [...body!.matchAll(/<>([\s\S]*?)<\/>/g)].map(m => m[1]!)

    for (const fragment of items.length > 0 ? items : [body!]) {
      const text = fragmentText(fragment)

      if (text) {
        out.push({ form: 'item', text })
      }
    }
  }

  return out
}

function pagesUnder(dir: string): string[] {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name)

    return statSync(path).isDirectory() ? pagesUnder(path) : name.endsWith('.tsx') ? [path] : []
  })
}

// the page's address: its path under the body, with `index` dropped
function routeOf(path: string): string {
  const rel = relative(BODY(), path)
    .slice(0, -'.tsx'.length)
    .replace(/(^|\/)index$/, '')

  return rel ? `/guides/${rel}` : '/guides'
}

const lines: string[] = []
let items = 0
let pages = 0

for (const path of pagesUnder(BODY()).sort((a, b) => routeOf(a).localeCompare(routeOf(b)))) {
  const section = sectionOf(readFileSync(path, 'utf8'))
  const entries = section === undefined ? [] : entriesOf(section)

  if (entries.length === 0) {
    continue
  }

  pages++
  lines.push(`## ${routeOf(path)}`, '')

  for (const entry of entries) {
    if (entry.form === 'code') {
      lines.push('```' + entry.kind, entry.text.trimEnd(), '```')
    } else {
      items++
      lines.push(`- ${entry.text}`)
    }
  }

  lines.push('')
}

const text = [
  '# What the guides say is missing',
  '',
  'Every `What is missing` section of the term.surf guides, verbatim, page by page. Generated by',
  '`pnpm term:guide-gaps --commit` from',
  '`mesh/site/term.surf/home/site/component/page/guides/body/`. Do not edit it by hand: change the page,',
  'then regenerate. The plan that works through it is [plan.md](plan.md).',
  '',
  `${items} items on ${pages} pages.`,
  '',
  ...lines,
].join('\n')

if (COMMIT) {
  mkdirSync(dirname(OUT()), { recursive: true })
  writeFileSync(OUT(), text)
  console.log(`wrote ${relative(ROOT, OUT())}: ${items} items on ${pages} pages`)
} else {
  console.log(text)
  console.log(`\n${items} items on ${pages} pages (--commit writes ${relative(ROOT, OUT())})`)
}
