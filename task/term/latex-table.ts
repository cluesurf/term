// THE LATEX COMMAND TABLE, generated from KaTeX's own registries: every symbol, function, environment and builtin
// macro KaTeX knows, with the signature the reader needs to parse it, into deck/mill/code/text/latex/table.tree. The
// reader (./read.tree beside it) is the parser and this table is its registry, the way @term/base/unit is the `note`
// grammar's: what `\frac` takes is the table's to say, never the reader's to guess.
//
// KaTeX is read from its source, not from a build, so the table is exactly the parser it was generated from. Every
// function spec must map to a handler the reader implements (HANDLERS below), and an unmapped spec FAILS the run: a
// KaTeX that grows a command the reader has no handler for is a change to stop at, not a row to write.
//
//   pnpm term:latex-table                 report what would change
//   pnpm term:latex-table --commit        write table.tree
//   pnpm term:latex-table --check         write nothing, exit 1 when table.tree is not what KaTeX gives
//   --katex <dir>                         a KaTeX checkout (default: land/code/github.com/KaTeX/KaTeX beside this repo)
//
// note/term/mill/04-latex-grammar.md.

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { TERM_ROOT, parentRoot } from './root'

const ROOT = TERM_ROOT
const TABLE = join(TERM_ROOT, 'deck/mill/code/text/latex/table.tree')
const GRAMMAR = join(TERM_ROOT, 'deck/mill/code/text/latex/mine.tree')

// ---- the `\verb` rules at the end of the grammar ----
//
// KaTeX's lexer closes a `\verb` with the character it opened with (`\\verb\*([^]).*?\4`, `\\verb([^*a-zA-Z]).*?\5`),
// a back reference no rule of a grammar can state once, so the grammar states it once for each delimiter. Every
// printable ASCII character is one for `\verb*`, every one but a letter and `*` for `\verb`. What stands between the
// delimiters is anything on the line, `.` in KaTeX's pattern: not the delimiter, a line feed, a carriage return, U+2028
// or U+2029.

const VERB_MARK = '# ---- the `\\verb` delimiters: GENERATED by `pnpm term:latex-table --commit` from here to the end ----'

function hex(code: number): string {
  return code.toString(16).padStart(4, '0')
}

function verbTail(): string {
  const starred: string[] = []
  const plain: string[] = []
  const lines = [VERB_MARK, '']

  for (let code = 0x20; code <= 0x7e; code++) {
    const letter = (code >= 0x41 && code <= 0x5a) || (code >= 0x61 && code <= 0x7a)

    starred.push(hex(code))

    if (!letter && code !== 0x2a) {
      plain.push(hex(code))
    }
  }

  lines.push('mine verb-starred-body', '  mine any', ...starred.map(h => `    mine form, form verb-delimited-${h}`), '')
  lines.push('mine verb-plain', '  mine any', ...plain.map(h => `    mine form, form verb-delimited-${h}`), '')

  for (const h of starred) {
    lines.push(
      `mine verb-delimited-${h}`,
      `  mine char, code 0x${h}`,
      `  mine form, form verb-content-${h}`,
      `  mine char, code 0x${h}`,
      '',
      `mine verb-content-${h}`,
      '  mine list',
      '    mine not',
      `      mine char, code 0x${h}`,
      '      mine char, code 0x000a',
      '      mine char, code 0x000d',
      '      mine char, code 0x2028',
      '      mine char, code 0x2029',
      '    mine range',
      '      bind base, code 0x0000',
      '      bind head, code 0x10ffff',
      '',
    )
  }

  return lines.join('\n')
}

// the grammar with its `\verb` tail written afresh: everything before the mark is the hand-written grammar
function grammarWithTail(): string {
  const text = readFileSync(GRAMMAR, 'utf8')
  const at = text.indexOf(VERB_MARK)
  const head = (at < 0 ? text : text.slice(0, at)).replace(/\n*$/, '\n\n')

  return head + verbTail()
}

function option(name: string): string | undefined {
  const at = process.argv.indexOf(name)

  return at < 0 ? undefined : process.argv[at + 1]
}

const KATEX = resolve(option('--katex') ?? join(parentRoot(), '../../land/code/github.com/KaTeX/KaTeX'))

async function load<T>(path: string): Promise<T> {
  return (await import(pathToFileURL(join(KATEX, path)).href)) as T
}

// ---- KaTeX's registries ----

type Spec = {
  type: string
  numArgs: number
  numOptionalArgs?: number
  argTypes?: string[]
  allowedInText?: boolean
  allowedInMath?: boolean
  allowedInArgument?: boolean
  infix?: boolean
  primitive?: boolean
}

type SymbolInfo = { font: string; group: string; replace?: string | null }

type Registries = {
  functions: Record<string, Spec>
  environments: Record<string, Spec>
  macros: Record<string, unknown>
  symbols: Record<string, Record<string, SymbolInfo>>
  scripts: { uSubsAndSups: Record<string, string>; unicodeSubRegEx: RegExp }
  accents: Record<string, { text: string; math?: string }>
  composed: Record<string, string>
}

async function registries(): Promise<Registries> {
  const { _functions } = await load<{ _functions: Record<string, Spec> }>('src/defineFunction.ts')
  const { _environments } = await load<{ _environments: Record<string, Spec> }>('src/defineEnvironment.ts')
  const { _macros } = await load<{ _macros: Record<string, unknown> }>('src/defineMacro.ts')

  await load('src/functions.ts')
  await load('src/environments.ts')
  await load('src/macros.ts')

  return {
    functions: _functions,
    environments: _environments,
    macros: _macros,
    symbols: (await load<{ default: Registries['symbols'] }>('src/symbols.ts')).default,
    scripts: await load<Registries['scripts']>('src/unicodeSupOrSub.ts'),
    accents: (await load<{ default: Registries['accents'] }>('src/unicodeAccents.js')).default,
    composed: (await load<{ default: Registries['composed'] }>('src/unicodeSymbols.js')).default,
  }
}

function commitOf(dir: string): string {
  try {
    return execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
}

