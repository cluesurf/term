mod fmath {
    pub fn sqrt(v: f64) -> f64 { v.sqrt() }
    pub fn floor(v: f64) -> f64 { v.floor() }
    pub fn ceil(v: f64) -> f64 { v.ceil() }
    pub fn round(v: f64) -> f64 { v.round() }
    pub fn pow(base: f64, exponent: f64) -> f64 { base.powf(exponent) }
    pub fn abs(v: f64) -> f64 { v.abs() }
    pub fn sin(v: f64) -> f64 { v.sin() }
    pub fn cos(v: f64) -> f64 { v.cos() }
}
